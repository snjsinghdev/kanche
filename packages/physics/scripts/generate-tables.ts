/**
 * Generates the committed lookup tables in src/params/v1/*.generated.ts.
 *
 *   node packages/physics/scripts/generate-tables.ts
 *
 * The simulation may not call sin or cos (ADR-0004), so directions come from tables computed
 * here offline. Values are computed in 256-bit BigInt fixed point (π by Machin's formula, sin
 * and cos by Taylor series) and rounded once to the nearest double, so the output never depends
 * on an engine's Math.cos. test/tables.test.ts regenerates the tables and compares them with the
 * committed file.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const BITS = 256n;
const ONE = 1n << BITS;

/** Directions in the start-point table: a full turn in this many equal steps. */
export const DIRECTION_COUNT = 1024;
/** The table stores the first octant only (0 to 45°, inclusive); symmetry gives the rest. */
export const OCTANT_STEPS = DIRECTION_COUNT / 8;
/** Lofted-shot lift angles: index k is k·LIFT_STEP_DEG degrees. */
export const LIFT_COUNT = 16;
export const LIFT_STEP_DEG = 3;

function atanInv(x: bigint): bigint {
  // atan(1/x) = sum (-1)^k / ((2k+1) x^(2k+1))
  let sum = 0n;
  let term = ONE / x;
  const x2 = x * x;
  for (let k = 0n; term !== 0n; k += 1n) {
    const t = term / (2n * k + 1n);
    sum += k % 2n === 0n ? t : -t;
    term /= x2;
  }
  return sum;
}

const PI = 16n * atanInv(5n) - 4n * atanInv(239n);

/** sin and cos of a fixed-point angle (radians × 2^BITS), |angle| <= π/4 for fast convergence. */
function sinCos(angle: bigint): { sin: bigint; cos: bigint } {
  let sin = 0n;
  let cos = 0n;
  let term = ONE; // angle^n / n! in fixed point
  for (let n = 0n; term !== 0n; n += 1n) {
    const sign = (n / 2n) % 2n === 0n ? 1n : -1n;
    if (n % 2n === 0n) cos += sign * term;
    else sin += sign * term;
    term = (term * angle) / ONE / (n + 1n);
  }
  return { sin, cos };
}

/** Round a fixed-point value in (-2, 2) to the nearest double (ties to even). */
export function fixedToDouble(value: bigint): number {
  if (value === 0n) return 0;
  const negative = value < 0n;
  const mag = negative ? -value : value;
  const bitLength = BigInt(mag.toString(2).length);
  const shift = bitLength - 53n;
  let mantissa = mag >> shift;
  const rest = mag - (mantissa << shift);
  const half = 1n << (shift - 1n);
  if (rest > half || (rest === half && (mantissa & 1n) === 1n)) mantissa += 1n;
  // value = mantissa · 2^(shift - BITS); the power of two is applied exactly by halving.
  let result = Number(mantissa);
  for (let e = shift - BITS; e < 0n; e += 1n) result /= 2;
  return negative ? -result : result;
}

/** [cos, sin] of 2πk/DIRECTION_COUNT for k = 0..OCTANT_STEPS. */
export function octantTable(): [number, number][] {
  const rows: [number, number][] = [];
  for (let k = 0; k <= OCTANT_STEPS; k += 1) {
    const angle = (2n * PI * BigInt(k)) / BigInt(DIRECTION_COUNT);
    const { sin, cos } = sinCos(angle);
    rows.push([fixedToDouble(cos), fixedToDouble(sin)]);
  }
  return rows;
}

/** [cos, sin] of the lift angles k·LIFT_STEP_DEG°, k = 0..LIFT_COUNT-1. */
export function liftTable(): [number, number][] {
  const rows: [number, number][] = [];
  for (let k = 0; k < LIFT_COUNT; k += 1) {
    const angle = (PI * BigInt(k * LIFT_STEP_DEG)) / 180n;
    const { sin, cos } = sinCos(angle);
    rows.push([fixedToDouble(cos), fixedToDouble(sin)]);
  }
  return rows;
}

function render(): string {
  const rows = (table: [number, number][]): string =>
    table.map(([c, s]) => `  [${String(c)}, ${String(s)}],`).join('\n');
  return `// Generated by packages/physics/scripts/generate-tables.ts. Do not edit by hand.
// Checked by test/tables.test.ts, which regenerates the values and compares them.

/** Directions in the start-point table: a full turn in this many equal steps. */
export const DIRECTION_COUNT = ${String(DIRECTION_COUNT)};

/** [cos, sin] of 2πk/${String(DIRECTION_COUNT)} for k = 0..${String(OCTANT_STEPS)} (the first octant, 0–45° inclusive). */
export const DIRECTION_OCTANT: readonly (readonly [number, number])[] = [
${rows(octantTable())}
];

/** Lofted-shot lift angles: [cos, sin] of k·${String(LIFT_STEP_DEG)}° for k = 0..${String(LIFT_COUNT - 1)}. */
export const LIFT_TABLE: readonly (readonly [number, number])[] = [
${rows(liftTable())}
];
`;
}

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'params', 'v1', 'directions.generated.ts');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  execFileSync('pnpm', ['exec', 'prettier', '--write', OUT], { stdio: 'inherit' });
  console.log(`wrote ${OUT}`);
}
